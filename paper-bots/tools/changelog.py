#!/usr/bin/env python3
"""Change log of every merged PR, newest first, from git history. Paper only.

    python3 paper-bots/tools/changelog.py                 # print Markdown
    python3 paper-bots/tools/changelog.py --write         # refresh paper-bots/docs/CHANGELOG.md
    python3 paper-bots/tools/changelog.py --days 7        # what changed this week

Each line: date (Central time), PR number, title. Rule changes (floors, caps,
sizing, timers, gates, shadow promotions) are marked "rule" so they are easy to
find. The boss dashboard and the Friday report can read the same lines.
"""
from __future__ import annotations

import argparse
import datetime as dt
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(os.path.dirname(HERE), "docs", "CHANGELOG.md")
RULE_WORDS = ("floor", "cap", "size", "sizing", "stake", "timer", "gate", "edge", "promote", "promotion",
              "limit", "stop", "max_open", "fee", "rule", "lock")

try:
    from zoneinfo import ZoneInfo
    CT = ZoneInfo("America/Chicago")
except Exception:  # noqa: BLE001
    CT = dt.timezone(dt.timedelta(hours=-6))


def parse(lines: list) -> list:
    """``<unix time>\\t<subject>`` lines into rows: date, pr, title, rule."""
    rows = []
    for line in lines:
        if "\t" not in line:
            continue
        stamp, subject = line.split("\t", 1)
        match = re.search(r"\(#(\d+)\)\s*$", subject)
        if not match:
            continue
        title = subject[: match.start()].strip()
        when = dt.datetime.fromtimestamp(int(stamp), dt.timezone.utc).astimezone(CT)
        low = title.lower()
        rows.append({"date": when.date().isoformat(), "pr": int(match.group(1)), "title": title,
                     "rule": any(re.search(rf"\b{w}", low) for w in RULE_WORDS)})
    return rows


def git_rows(ref: str = "origin/main") -> list:
    out = subprocess.run(["git", "-C", REPO, "log", "--first-parent", "--format=%ct\t%s", ref],
                         capture_output=True, text=True, check=True).stdout
    return parse(out.splitlines())


def since(rows: list, days: int, today: dt.date | None = None) -> list:
    today = today or dt.datetime.now(CT).date()
    cut = (today - dt.timedelta(days=days)).isoformat()
    return [r for r in rows if r["date"] > cut]


def markdown(rows: list, head: str = "# Change log") -> str:
    lines = [head, "", "Every merged PR, newest first. \"rule\" marks a change to floors, caps, sizing, "
             "timers, gates or promotions. Generated by paper-bots/tools/changelog.py.", ""]
    day = None
    for row in rows:
        if row["date"] != day:
            day = row["date"]
            lines += ["", f"## {day}", ""]
        tag = " (rule)" if row["rule"] else ""
        lines.append(f"- #{row['pr']}{tag}: {row['title']}")
    return "\n".join(lines).replace("\n\n\n", "\n\n") + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--days", type=int, default=0)
    parser.add_argument("--ref", default="origin/main")
    args = parser.parse_args(argv)
    rows = git_rows(args.ref)
    if args.days:
        rows = since(rows, args.days)
    text = markdown(rows, f"# What changed in the last {args.days} days" if args.days else "# Change log")
    if args.write:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w", encoding="utf-8") as handle:
            handle.write(text)
        print(f"Wrote {len(rows)} rows.")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
